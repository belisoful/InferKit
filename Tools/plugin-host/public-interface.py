#!/usr/bin/env python3
"""Writes Sources/InferKit/NFKPluginPublicInterface.m: a table that names every constant and function the
public headers declare, which NFKPluginRetainPublicInterface reads so a dead-stripped link keeps them.

An "objc" plugin binds to the InferKit already loaded in its process by name, so the plugin host (and an
app that links InferKit statically and trusts plugins in its process) must keep every public symbol, the
ones it never references itself included. A release link drops those.

    Tools/plugin-host/public-interface.py           # rewrites the table
    Tools/plugin-host/public-interface.py --check   # exits 1 when the table is stale

Rerun it whenever a public header adds or removes a constant or a function.
"""

import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADERS = [os.path.join(ROOT, "Sources/InferKit/include/InferKit"), os.path.join(ROOT, "Sources/InferKitC/include/InferKitC")]
OUTPUT = os.path.join(ROOT, "Sources/InferKit/NFKPluginPublicInterface.m")
# Implemented by a plugin, not by InferKit.
EXCLUDED = {"nfk_plugin_entry"}

MACRO=re.compile(r'\b(API_UNAVAILABLE|API_AVAILABLE|NS_SWIFT_NAME|NS_SWIFT_UNAVAILABLE|NS_REFINED_FOR_SWIFT|__attribute__|NS_SWIFT_SENDABLE|NS_FORMAT_FUNCTION|NS_RETURNS_RETAINED|CF_RETURNS_RETAINED|NS_SWIFT_NOTHROW|CF_SWIFT_NAME)\s*(\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))?')
def symbols(path):
    text=open(path).read()
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S); text=re.sub(r'//[^\n]*','',text)
    text=re.sub(r'^\s*#.*?(?<!\\)$','',text,flags=re.M|re.S)
    text=re.sub(r'@(interface|protocol|implementation)\b.*?@end','',text,flags=re.S)
    text=re.sub(r'\b(typedef|struct|union|enum)\b[^;]*?\{[^{}]*(\{[^{}]*\}[^{}]*)*\}[^;]*;','',text,flags=re.S)
    found=[]
    for st in text.split(';'):
        st=MACRO.sub('',st).strip()
        st=re.sub(r'\bNS_ASSUME_NONNULL_(BEGIN|END)\b','',st).strip()
        st=re.sub(r'^(extern\s+"C"\s*\{|\})\s*','',st).strip()
        if not st or st.startswith('typedef') or st.startswith('@') or re.match(r'(struct|enum|union)\b',st): continue
        if '(' in st:
            m=re.search(r'\b(NFK\w+|nfk_\w+)\s*\(',st)
            if m and not re.search(r'\(\s*\^',st[:m.start()]): found.append(('function',m.group(1)))
        else:
            if not re.match(r'(extern|FOUNDATION_EXPORT)\b',st): continue
            name=re.findall(r'\b([A-Za-z_]\w*)\b',st)[-1]
            found.append(('constant',name))
    return found


def table():
    names = []
    for directory in HEADERS:
        for path in sorted(glob.glob(os.path.join(directory, "*.h"))):
            for kind, name in symbols(path):
                if name not in EXCLUDED and name not in names:
                    names.append(name)
    lines = [
        "//",
        "//  NFKPluginPublicInterface.m",
        "//  InferKit",
        "//",
        "//  Generated by Tools/plugin-host/public-interface.py from the public headers. Do not edit.",
        "//",
        "",
        "#import <TargetConditionals.h>",
        "",
        "#if TARGET_OS_OSX",
        "",
        "#import \"InferKit.h\"",
        "#import <InferKitC/NFKInferKitC.h>",
        "",
        "/*! Every constant and function the public headers declare. */",
        "static const void *const NFKPluginPublicInterface[] = {",
    ]
    lines += ["\t(const void *)&%s," % name for name in names]
    lines += [
        "};",
        "",
        "NSUInteger NFKPluginRetainPublicInterface(void)",
        "{",
        "\t// Read through a volatile pointer, so neither the table nor a symbol it names is optimized away.",
        "\tconst void *const volatile *entries = NFKPluginPublicInterface;",
        "\tNSUInteger present = 0;",
        "\tfor (NSUInteger index = 0; index < sizeof NFKPluginPublicInterface / sizeof *NFKPluginPublicInterface; index++) {",
        "\t\tif (entries[index] != NULL) {",
        "\t\t\tpresent += 1;",
        "\t\t}",
        "\t}",
        "\treturn present;",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines), names


def main():
    text, names = table()
    if "--check" in sys.argv[1:]:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ""
        if current != text:
            sys.stderr.write("NFKPluginPublicInterface.m is stale: run Tools/plugin-host/public-interface.py\n")
            return 1
        print("%d public symbols, table current" % len(names))
        return 0
    with open(OUTPUT, "w") as handle:
        handle.write(text)
    print("wrote %s: %d public symbols" % (os.path.relpath(OUTPUT, ROOT), len(names)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
